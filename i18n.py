def translate(text: str, language: str = "Français", *, allow_fallback: bool = True) -> str:
    """Translate a supported interface label; French is the canonical fallback."""
    # Keep the product name visually consistent in every translated UI label.
    # This changes display text only; internal route keys and Python identifiers
    # remain untouched.
    text = str(text).replace("SOWIA", "SOW IA").replace("Sowia", "SOW IA")
    if language not in LANGUAGES:
        language = "Français"
    translated = _POST_LOGIN_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    # Preserve common Markdown wrappers while translating their visible text.
    # This covers headings, bold/italic labels and simple list entries without
    # changing Markdown structure or user-authored content.
    for _heading_prefix in ("###### ", "##### ", "#### ", "### ", "## ", "# "):
        if text.startswith(_heading_prefix):
            _heading = text[len(_heading_prefix):]
            _translated_heading = translate(_heading, language, allow_fallback=allow_fallback)
            if _translated_heading != _heading:
                return _heading_prefix + _translated_heading
            break
    for _prefix in ("- ", "• ", "1. ", "2. ", "3. "):
        if text.startswith(_prefix):
            _item = text[len(_prefix):]
            _translated_item = translate(_item, language, allow_fallback=allow_fallback)
            if _translated_item != _item:
                return _prefix + _translated_item
            break
    for _marker in ("**", "__", "~~", "*", "_"):
        if text.startswith(_marker) and text.endswith(_marker) and len(text) > 2 * len(_marker):
            _inner = text[len(_marker):-len(_marker)]
            _translated_inner = translate(_inner, language, allow_fallback=allow_fallback)
            if _translated_inner != _inner:
                return _marker + _translated_inner + _marker
            break
    # Merge the original catalogue with the additional navigation labels.
    # Separate dictionaries prevent duplicate language keys from overwriting
    # the broader translation catalogue during module loading.
    translated = _BASE_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _EXTRA_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _AUTH_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _CORE_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _COMMON_UI_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated

    # Last-resort translation for interface copy missing from the curated
    # catalogue. The result is cached so the external service is not called
    # again for the same label during normal reruns.
    return _translate_missing_interface_copy(text, language) if allow_fallback else text


_LANGUAGE_CODES = {
    "English": "en",
    "Español": "es",
    "中文": "zh-CN",
    "Deutsch": "de",
    "العربية": "ar",
}


@__import__("functools").lru_cache(maxsize=4096)
def _translate_missing_interface_copy(text: str, language: str) -> str:
    """Translate uncatalogued short UI copy; preserve content on any failure."""
    import re
    import requests

    if language not in _LANGUAGE_CODES or not text or len(text) > 240:
        return text
    # Do not send code, HTML, URLs, multiline documents or user-authored
    # paragraphs to a translation service.
    if (
        "\n" in text
        or re.search(r"</?[A-Za-z][^>]*>|https?://|www\.", text)
        or text.lstrip().startswith(("```", "{", "["))
    ):
        return text
    try:
        response = requests.get(
            "https://translate.googleapis.com/translate_a/single",
            params={
                "client": "gtx",
                "sl": "fr",
                "tl": _LANGUAGE_CODES[language],
                "dt": "t",
                "q": text,
            },
            timeout=(2, 4),
        )
        response.raise_for_status()
        payload = response.json()
        result = "".join(
            segment[0]
            for segment in (payload[0] or [])
            if isinstance(segment, list) and segment and isinstance(segment[0], str)
        )
        return result.strip() if result.strip() else text
    except Exception:
        # Translation outages must never prevent the user from using SOW IA.
        return text
