def translate(text: str, language: str = "Français") -> str:
    """Translate a supported interface label; French is the canonical fallback."""
    # Keep the product name visually consistent in every translated UI label.
    # This changes display text only; internal route keys and Python identifiers
    # remain untouched.
    text = str(text).replace("SOWIA", "SOW IA").replace("Sowia", "SOW IA")
    if language not in LANGUAGES:
        language = "Français"
    # Keep Markdown heading markers while translating their visible title.
    for _heading_prefix in ("###### ", "##### ", "#### ", "### ", "## ", "# "):
        if text.startswith(_heading_prefix):
            _heading = text[len(_heading_prefix):]
            _translated_heading = translate(_heading, language)
            if _translated_heading != _heading:
                return _heading_prefix + _translated_heading
            break
    # Merge the original catalogue with the additional navigation labels.
    # Separate dictionaries prevent duplicate language keys from overwriting
    # the broader translation catalogue during module loading.
    translated = _BASE_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _EXTRA_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _AUTH_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    translated = _CORE_TRANSLATIONS.get(language, {}).get(text)
    if translated is not None:
        return translated
    return _COMMON_UI_TRANSLATIONS.get(language, {}).get(text, text)
