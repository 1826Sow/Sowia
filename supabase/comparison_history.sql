-- Persistent private SOW IA comparison history. Run once in Supabase SQL Editor.
create table if not exists public.sowia_comparison_history (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    report jsonb not null,
    created_at timestamptz not null default now(),
    constraint sowia_comparison_history_report_size check (pg_column_size(report) <= 250000)
);

create index if not exists sowia_comparison_history_user_created_idx
    on public.sowia_comparison_history (user_id, created_at desc);

alter table public.sowia_comparison_history enable row level security;

drop policy if exists "Users can read their own SOW IA comparison history" on public.sowia_comparison_history;
create policy "Users can read their own SOW IA comparison history"
    on public.sowia_comparison_history for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA comparison history" on public.sowia_comparison_history;
create policy "Users can add their own SOW IA comparison history"
    on public.sowia_comparison_history for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA comparison history" on public.sowia_comparison_history;
create policy "Users can delete their own SOW IA comparison history"
    on public.sowia_comparison_history for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, delete on public.sowia_comparison_history to authenticated;
grant usage, select on sequence public.sowia_comparison_history_id_seq to authenticated;
