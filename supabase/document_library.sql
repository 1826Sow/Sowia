-- SOW IA private document library. Run once in Supabase SQL Editor.
create table if not exists public.sowia_documents (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    title text not null check (char_length(title) between 1 and 160),
    filename text not null check (char_length(filename) between 1 and 255),
    extracted_text text not null check (char_length(extracted_text) between 1 and 100000),
    text_length integer not null check (text_length between 1 and 100000),
    created_at timestamptz not null default now()
);

create index if not exists sowia_documents_user_created_idx
    on public.sowia_documents (user_id, created_at desc);

alter table public.sowia_documents enable row level security;

drop policy if exists "Users can read their own SOW IA documents" on public.sowia_documents;
create policy "Users can read their own SOW IA documents"
    on public.sowia_documents for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA documents" on public.sowia_documents;
create policy "Users can add their own SOW IA documents"
    on public.sowia_documents for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA documents" on public.sowia_documents;
create policy "Users can delete their own SOW IA documents"
    on public.sowia_documents for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, delete on public.sowia_documents to authenticated;
grant usage, select on all sequences in schema public to authenticated;
