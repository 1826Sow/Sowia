-- SOW IA Business Club: opt-in company directory and private meeting requests.
-- Run once in Supabase SQL Editor. Safe to re-run; existing records are preserved.
create table if not exists public.sowia_business_club_profiles (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 workspace_id text not null default 'professional' check (workspace_id in ('personal','professional')),
 company_name text not null check (char_length(company_name) between 1 and 180),
 country text not null check (char_length(country) between 1 and 100),
 sector text not null check (char_length(sector) between 1 and 100),
 description text not null default '' check (char_length(description) <= 1200),
 offers text[] not null default '{}', needs text[] not null default '{}', objectives text[] not null default '{}',
 website text, is_published boolean not null default false,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique (user_id, workspace_id)
);
create table if not exists public.sowia_business_club_requests (
 id bigint generated by default as identity primary key,
 profile_id bigint not null references public.sowia_business_club_profiles(id) on delete cascade,
 sender_user_id uuid not null references auth.users(id) on delete cascade,
 recipient_user_id uuid not null references auth.users(id) on delete cascade,
 message text not null check (char_length(message) between 1 and 1200),
 status text not null default 'En attente' check (status in ('En attente','Acceptée','Refusée','Annulée')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 check (sender_user_id <> recipient_user_id)
);
create index if not exists sowia_club_profiles_directory_idx on public.sowia_business_club_profiles (is_published,country,sector);
create index if not exists sowia_club_requests_recipient_idx on public.sowia_business_club_requests (recipient_user_id,status,created_at desc);
create index if not exists sowia_club_requests_sender_idx on public.sowia_business_club_requests (sender_user_id,status,created_at desc);
alter table public.sowia_business_club_profiles enable row level security;
alter table public.sowia_business_club_requests enable row level security;
drop policy if exists "Club profiles visible when published or owned" on public.sowia_business_club_profiles;
create policy "Club profiles visible when published or owned" on public.sowia_business_club_profiles for select to authenticated using (is_published or (select auth.uid()) = user_id);
drop policy if exists "Users can create their own club profile" on public.sowia_business_club_profiles;
create policy "Users can create their own club profile" on public.sowia_business_club_profiles for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own club profile" on public.sowia_business_club_profiles;
create policy "Users can update their own club profile" on public.sowia_business_club_profiles for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own club profile" on public.sowia_business_club_profiles;
create policy "Users can delete their own club profile" on public.sowia_business_club_profiles for delete to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Participants can read their club requests" on public.sowia_business_club_requests;
create policy "Participants can read their club requests" on public.sowia_business_club_requests for select to authenticated using ((select auth.uid()) = sender_user_id or (select auth.uid()) = recipient_user_id);
drop policy if exists "Members can request a published club meeting" on public.sowia_business_club_requests;
create policy "Members can request a published club meeting" on public.sowia_business_club_requests for insert to authenticated with check (
 (select auth.uid()) = sender_user_id and sender_user_id <> recipient_user_id and exists (
  select 1 from public.sowia_business_club_profiles p where p.id = profile_id and p.user_id = recipient_user_id and p.is_published
 ));
drop policy if exists "Recipients can respond to club requests" on public.sowia_business_club_requests;
create policy "Recipients can respond to club requests" on public.sowia_business_club_requests for update to authenticated using ((select auth.uid()) = recipient_user_id and status = 'En attente') with check ((select auth.uid()) = recipient_user_id and status in ('Acceptée','Refusée'));
drop policy if exists "Senders can cancel pending club requests" on public.sowia_business_club_requests;
create policy "Senders can cancel pending club requests" on public.sowia_business_club_requests for update to authenticated using ((select auth.uid()) = sender_user_id and status = 'En attente') with check ((select auth.uid()) = sender_user_id and status = 'Annulée');
grant select,insert,update,delete on public.sowia_business_club_profiles to authenticated;
grant select,insert,update on public.sowia_business_club_requests to authenticated;
grant usage,select on sequence public.sowia_business_club_profiles_id_seq to authenticated;
grant usage,select on sequence public.sowia_business_club_requests_id_seq to authenticated;


-- Meeting proposals require an accepted underlying meeting request.
create table if not exists public.sowia_business_club_meetings (
 id bigint generated by default as identity primary key,
 request_id bigint not null references public.sowia_business_club_requests(id) on delete cascade,
 organizer_user_id uuid not null references auth.users(id) on delete cascade,
 sender_user_id uuid not null references auth.users(id) on delete cascade,
 recipient_user_id uuid not null references auth.users(id) on delete cascade,
 invitee_user_id uuid not null references auth.users(id) on delete cascade,
 starts_at timestamptz not null,
 timezone text not null check (char_length(timezone) between 1 and 80),
 duration_minutes integer not null check (duration_minutes in (15,30,45,60)),
 meeting_url text check (meeting_url is null or meeting_url like 'https://%'),
 status text not null default 'Proposée' check (status in ('Proposée','Confirmée','Refusée','Annulée')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 check (sender_user_id <> recipient_user_id),
 check (organizer_user_id = sender_user_id or organizer_user_id = recipient_user_id)
);
alter table public.sowia_business_club_meetings add column if not exists invitee_user_id uuid references auth.users(id) on delete cascade;
create index if not exists sowia_club_meetings_participants_idx
 on public.sowia_business_club_meetings (sender_user_id, recipient_user_id, starts_at);
alter table public.sowia_business_club_meetings enable row level security;
drop policy if exists "Participants can read club meetings" on public.sowia_business_club_meetings;
create policy "Participants can read club meetings" on public.sowia_business_club_meetings
 for select to authenticated using ((select auth.uid()) = sender_user_id or (select auth.uid()) = recipient_user_id);
drop policy if exists "Participants can propose club meetings" on public.sowia_business_club_meetings;
create policy "Participants can propose club meetings" on public.sowia_business_club_meetings
 for insert to authenticated with check (
  (select auth.uid()) = organizer_user_id and exists (
   select 1 from public.sowia_business_club_requests r
   where r.id = request_id and r.status = 'Acceptée'
   and r.sender_user_id = sender_user_id and r.recipient_user_id = recipient_user_id
   and ((select auth.uid()) = r.sender_user_id or (select auth.uid()) = r.recipient_user_id)
  )
 );
drop policy if exists "Invitees can respond to club meetings" on public.sowia_business_club_meetings;
create policy "Invitees can respond to club meetings" on public.sowia_business_club_meetings
 for update to authenticated using ((select auth.uid()) = invitee_user_id and status = 'Proposée')
 with check ((select auth.uid()) = invitee_user_id and status in ('Confirmée','Refusée'));
drop policy if exists "Organizers can cancel proposed club meetings" on public.sowia_business_club_meetings;
create policy "Organizers can cancel proposed club meetings" on public.sowia_business_club_meetings
 for update to authenticated using ((select auth.uid()) = organizer_user_id and status = 'Proposée')
 with check ((select auth.uid()) = organizer_user_id and status = 'Annulée');
grant select, insert, update on public.sowia_business_club_meetings to authenticated;
grant usage, select on sequence public.sowia_business_club_meetings_id_seq to authenticated;
