-- SOW IA Business Club: private in-app notifications.
-- Run after supabase_business_club.sql in the Supabase SQL Editor.
-- Notifications are created by database triggers; users can only read and mark their own as read.

create table if not exists public.sowia_business_club_notifications (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 event_type text not null check (event_type in ('request_received','request_accepted','request_refused','meeting_proposed','meeting_confirmed','meeting_refused','meeting_cancelled')),
 entity_type text not null check (entity_type in ('request','meeting')),
 entity_id bigint not null,
 message text not null check (char_length(message) between 1 and 240),
 created_at timestamptz not null default now(),
 read_at timestamptz,
 unique (user_id, event_type, entity_type, entity_id)
);

create index if not exists sowia_club_notifications_inbox_idx
 on public.sowia_business_club_notifications (user_id, read_at, created_at desc);

alter table public.sowia_business_club_notifications enable row level security;
drop policy if exists "Users read their own club notifications" on public.sowia_business_club_notifications;
create policy "Users read their own club notifications"
 on public.sowia_business_club_notifications for select to authenticated
 using ((select auth.uid()) = user_id);
drop policy if exists "Users mark their own club notifications read" on public.sowia_business_club_notifications;
create policy "Users mark their own club notifications read"
 on public.sowia_business_club_notifications for update to authenticated
 using ((select auth.uid()) = user_id and read_at is null)
 with check ((select auth.uid()) = user_id);
revoke all on public.sowia_business_club_notifications from anon, authenticated;
grant select on public.sowia_business_club_notifications to authenticated;
grant update (read_at) on public.sowia_business_club_notifications to authenticated;
grant usage, select on sequence public.sowia_business_club_notifications_id_seq to authenticated;

create or replace function public.sowia_club_notify_request_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
 if tg_op = 'INSERT' then
  insert into public.sowia_business_club_notifications
   (user_id,event_type,entity_type,entity_id,message)
  values (new.recipient_user_id,'request_received','request',new.id,'Nouvelle demande de mise en relation professionnelle');
 elsif old.status is distinct from new.status and new.status in ('Acceptée','Refusée') then
  insert into public.sowia_business_club_notifications
   (user_id,event_type,entity_type,entity_id,message)
  values (new.sender_user_id,
   case when new.status = 'Acceptée' then 'request_accepted' else 'request_refused' end,
   'request',new.id,
   case when new.status = 'Acceptée' then 'Votre demande de mise en relation a été acceptée' else 'Votre demande de mise en relation a été refusée' end);
 end if;
 return new;
end;
$$;

drop trigger if exists sowia_club_request_notification_trigger on public.sowia_business_club_requests;
create trigger sowia_club_request_notification_trigger
 after insert or update of status on public.sowia_business_club_requests
 for each row execute function public.sowia_club_notify_request_event();

create or replace function public.sowia_club_notify_meeting_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
 target_user uuid;
 notification_type text;
 notification_message text;
begin
 if tg_op = 'INSERT' then
  target_user := new.invitee_user_id;
  notification_type := 'meeting_proposed';
  notification_message := 'Un rendez-vous professionnel vous est proposé';
 elsif old.status is distinct from new.status and new.status in ('Confirmée','Refusée','Annulée') then
  target_user := new.organizer_user_id;
  notification_type := case new.status
   when 'Confirmée' then 'meeting_confirmed'
   when 'Refusée' then 'meeting_refused'
   else 'meeting_cancelled'
  end;
  notification_message := case new.status
   when 'Confirmée' then 'Votre rendez-vous professionnel est confirmé'
   when 'Refusée' then 'Votre proposition de rendez-vous a été refusée'
   else 'Le rendez-vous professionnel a été annulé'
  end;
 else
  return new;
 end if;
 insert into public.sowia_business_club_notifications
  (user_id,event_type,entity_type,entity_id,message)
 values (target_user,notification_type,'meeting',new.id,notification_message)
 on conflict (user_id,event_type,entity_type,entity_id) do nothing;
 return new;
end;
$$;

drop trigger if exists sowia_club_meeting_notification_trigger on public.sowia_business_club_meetings;
create trigger sowia_club_meeting_notification_trigger
 after insert or update of status on public.sowia_business_club_meetings
 for each row execute function public.sowia_club_notify_meeting_event();

revoke all on function public.sowia_club_notify_request_event() from public, anon, authenticated;
revoke all on function public.sowia_club_notify_meeting_event() from public, anon, authenticated;
