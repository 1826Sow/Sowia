-- SOW IA opportunity pipeline. Forecasts only: no payment or revenue ledger.
-- Run once in Supabase SQL Editor. Safe to re-run.
create table if not exists public.sowia_business_opportunities (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    workspace_id text not null default 'personal'
        check (workspace_id in ('personal', 'professional')),
    niche text not null check (char_length(niche) between 1 and 100),
    offer text not null check (char_length(offer) between 1 and 240),
    stage text not null default 'À étudier'
        check (stage in ('À étudier', 'À tester', 'En lancement', 'Active', 'Suspendue', 'Abandonnée')),
    expected_monthly_revenue numeric(14,2) not null default 0
        check (expected_monthly_revenue >= 0 and expected_monthly_revenue <= 1000000000),
    estimated_monthly_cost numeric(14,2) not null default 0
        check (estimated_monthly_cost >= 0 and estimated_monthly_cost <= 1000000000),
    currency text not null default 'EUR'
        check (currency in ('EUR', 'USD', 'GBP', 'CHF', 'CAD')),
    source_url text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists sowia_business_opportunities_owner_workspace_idx
    on public.sowia_business_opportunities (user_id, workspace_id, updated_at desc);

alter table public.sowia_business_opportunities enable row level security;
drop policy if exists "SOW IA users read own business opportunities" on public.sowia_business_opportunities;
create policy "SOW IA users read own business opportunities"
    on public.sowia_business_opportunities for select to authenticated
    using ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users insert own business opportunities" on public.sowia_business_opportunities;
create policy "SOW IA users insert own business opportunities"
    on public.sowia_business_opportunities for insert to authenticated
    with check ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users update own business opportunities" on public.sowia_business_opportunities;
create policy "SOW IA users update own business opportunities"
    on public.sowia_business_opportunities for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users delete own business opportunities" on public.sowia_business_opportunities;
create policy "SOW IA users delete own business opportunities"
    on public.sowia_business_opportunities for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.sowia_business_opportunities to authenticated;
grant usage, select on sequence public.sowia_business_opportunities_id_seq to authenticated;
