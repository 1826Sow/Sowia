-- Persistent partner CRM for SOW IA.
-- Run once in Supabase SQL Editor. Safe to re-run; existing data is preserved.
create table if not exists public.sowia_growth_leads (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    workspace_id text not null default 'personal'
        check (workspace_id in ('personal', 'professional')),
    organization text not null check (char_length(organization) between 1 and 180),
    country text not null check (char_length(country) between 1 and 100),
    region text not null default '',
    partner_type text not null default '',
    website text,
    source_url text,
    notes text,
    status text not null default 'À vérifier'
        check (status in (
            'À vérifier', 'À contacter', 'Contacté', 'Réponse reçue',
            'En discussion', 'Partenaire confirmé', 'Non pertinent'
        )),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.sowia_growth_leads
    add column if not exists workspace_id text not null default 'personal';

create index if not exists sowia_growth_leads_user_workspace_updated_idx
    on public.sowia_growth_leads (user_id, workspace_id, updated_at desc);

alter table public.sowia_growth_leads enable row level security;

drop policy if exists "Users can read their own SOW IA growth leads" on public.sowia_growth_leads;
create policy "Users can read their own SOW IA growth leads"
    on public.sowia_growth_leads for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA growth leads" on public.sowia_growth_leads;
create policy "Users can add their own SOW IA growth leads"
    on public.sowia_growth_leads for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own SOW IA growth leads" on public.sowia_growth_leads;
create policy "Users can update their own SOW IA growth leads"
    on public.sowia_growth_leads for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA growth leads" on public.sowia_growth_leads;
create policy "Users can delete their own SOW IA growth leads"
    on public.sowia_growth_leads for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.sowia_growth_leads to authenticated;
grant usage, select on sequence public.sowia_growth_leads_id_seq to authenticated;
