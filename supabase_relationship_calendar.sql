-- Private relationship calendar for SOW IA.
-- Run once in Supabase SQL Editor. Safe to re-run; existing CRM data is preserved.

create table if not exists public.sowia_relationship_events (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    workspace_id text not null default 'personal'
        check (workspace_id in ('personal', 'professional')),
    lead_id bigint references public.sowia_growth_leads(id) on delete set null,
    title text not null check (char_length(title) between 1 and 160),
    event_type text not null check (event_type in (
        'Anniversaire personnel',
        'Anniversaire de l''entreprise',
        'Échéance de partenariat',
        'Relance commerciale',
        'Réunion / rendez-vous',
        'Renouvellement de contrat',
        'Suivi après échange',
        'Autre'
    )),
    due_date date not null,
    notes text,
    contact_authorized boolean not null default false,
    status text not null default 'À faire'
        check (status in ('À faire', 'Terminé', 'Annulé')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists sowia_relationship_events_user_workspace_date_idx
    on public.sowia_relationship_events (user_id, workspace_id, due_date);

alter table public.sowia_relationship_events enable row level security;

drop policy if exists "Users can read their own SOW IA relationship events"
    on public.sowia_relationship_events;
create policy "Users can read their own SOW IA relationship events"
    on public.sowia_relationship_events for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA relationship events"
    on public.sowia_relationship_events;
create policy "Users can add their own SOW IA relationship events"
    on public.sowia_relationship_events for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own SOW IA relationship events"
    on public.sowia_relationship_events;
create policy "Users can update their own SOW IA relationship events"
    on public.sowia_relationship_events for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA relationship events"
    on public.sowia_relationship_events;
create policy "Users can delete their own SOW IA relationship events"
    on public.sowia_relationship_events for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.sowia_relationship_events to authenticated;
grant usage, select on sequence public.sowia_relationship_events_id_seq to authenticated;
