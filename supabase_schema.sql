-- SOW IA: private per-user memory and conversation history.
-- Run this script once in Supabase > SQL Editor.
create table if not exists public.sowia_memory_items (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    content text not null check (char_length(content) between 1 and 1000),
    created_at timestamptz not null default now()
);

create table if not exists public.sowia_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text not null,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists sowia_memory_items_user_created_idx
    on public.sowia_memory_items (user_id, created_at desc);
create index if not exists sowia_messages_user_session_id_idx
    on public.sowia_messages (user_id, session_id, id desc);

alter table public.sowia_memory_items enable row level security;
alter table public.sowia_messages enable row level security;

drop policy if exists "Users can read their own SOW IA memories" on public.sowia_memory_items;
create policy "Users can read their own SOW IA memories"
    on public.sowia_memory_items for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA memories" on public.sowia_memory_items;
create policy "Users can add their own SOW IA memories"
    on public.sowia_memory_items for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA memories" on public.sowia_memory_items;
create policy "Users can delete their own SOW IA memories"
    on public.sowia_memory_items for delete to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can read their own SOW IA messages" on public.sowia_messages;
create policy "Users can read their own SOW IA messages"
    on public.sowia_messages for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own SOW IA messages" on public.sowia_messages;
create policy "Users can add their own SOW IA messages"
    on public.sowia_messages for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own SOW IA messages" on public.sowia_messages;
create policy "Users can delete their own SOW IA messages"
    on public.sowia_messages for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, delete on public.sowia_memory_items to authenticated;
grant select, insert, delete on public.sowia_messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Private PDF bucket: each authenticated user can access only objects
-- stored under their own auth.uid() folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'sowia-private-documents',
    'sowia-private-documents',
    false,
    10485760,
    array['application/pdf']
)
on conflict (id) do update set
    public = false,
    file_size_limit = 10485760,
    allowed_mime_types = array['application/pdf'];

drop policy if exists "SOW IA users can read their own documents" on storage.objects;
create policy "SOW IA users can read their own documents"
    on storage.objects for select to authenticated
    using (
        bucket_id = 'sowia-private-documents'
        and (storage.foldername(name))[1] = (select auth.uid())::text
    );

drop policy if exists "SOW IA users can upload their own documents" on storage.objects;
create policy "SOW IA users can upload their own documents"
    on storage.objects for insert to authenticated
    with check (
        bucket_id = 'sowia-private-documents'
        and (storage.foldername(name))[1] = (select auth.uid())::text
    );

drop policy if exists "SOW IA users can delete their own documents" on storage.objects;
create policy "SOW IA users can delete their own documents"
    on storage.objects for delete to authenticated
    using (
        bucket_id = 'sowia-private-documents'
        and (storage.foldername(name))[1] = (select auth.uid())::text
    );
