-- SOW IA technology comparison: persistent evaluations scoped to owner/workspace.
-- Run once in Supabase SQL Editor. Safe to re-run.
create table if not exists public.sowia_technology_candidates (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    workspace_id text not null default 'personal'
        check (workspace_id in ('personal', 'professional')),
    name text not null check (char_length(name) between 1 and 120),
    scores jsonb not null check (jsonb_typeof(scores) = 'object'),
    score numeric(5,1) not null check (score >= 0 and score <= 100),
    decision text not null check (decision in ('Prioritaire', 'À tester', 'À documenter', 'Non prioritaire', 'Écarter')),
    reasons jsonb not null default '[]'::jsonb check (jsonb_typeof(reasons) = 'array'),
    evidence jsonb not null default '[]'::jsonb check (jsonb_typeof(evidence) = 'array'),
    compliant boolean not null default true,
    compliance_verified boolean not null default false,
    critical_incident boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint sowia_technology_candidates_owner_workspace_name_key
        unique (user_id, workspace_id, name)
);

create index if not exists sowia_technology_candidates_owner_workspace_updated_idx
    on public.sowia_technology_candidates (user_id, workspace_id, updated_at desc);

alter table public.sowia_technology_candidates enable row level security;
drop policy if exists "SOW IA users read own technology candidates" on public.sowia_technology_candidates;
create policy "SOW IA users read own technology candidates"
    on public.sowia_technology_candidates for select to authenticated
    using ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users insert own technology candidates" on public.sowia_technology_candidates;
create policy "SOW IA users insert own technology candidates"
    on public.sowia_technology_candidates for insert to authenticated
    with check ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users update own technology candidates" on public.sowia_technology_candidates;
create policy "SOW IA users update own technology candidates"
    on public.sowia_technology_candidates for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);
drop policy if exists "SOW IA users delete own technology candidates" on public.sowia_technology_candidates;
create policy "SOW IA users delete own technology candidates"
    on public.sowia_technology_candidates for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, update, delete on public.sowia_technology_candidates to authenticated;
grant usage, select on sequence public.sowia_technology_candidates_id_seq to authenticated;
