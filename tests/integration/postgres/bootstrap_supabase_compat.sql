-- Minimal Supabase-compatible objects for isolated PostgreSQL migration/RLS tests.
-- This is test-only scaffolding; it does not replace Supabase Auth in production.
create schema if not exists auth;
create table if not exists auth.users (
  id uuid primary key,
  email text unique
);
create or replace function auth.uid()
returns uuid
language sql stable
as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;
end
$$;
grant usage on schema auth, public to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
grant select on auth.users to authenticated;
create table if not exists public.sowia_projects (
  id bigint generated by default as identity primary key,
  workspace_id text not null default 'personal',
  archived_at timestamptz,
  user_id uuid not null references auth.users(id)
);
create or replace function public.sowia_has_professional_access()
returns boolean language sql stable as $$ select false $$;
grant execute on function public.sowia_has_professional_access() to authenticated;
